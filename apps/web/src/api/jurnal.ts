// Typed client for the manual journal surface, spec 6 and spec 9.4's seven
// screens. The routes landed in apps/api/src/modules/jurnal/routes.ts.
//
// TYPES COME FROM THE CONTRACT AND FROM ./baca.ts, TYPE ONLY, exactly as
// ./tools.ts and ./closing.ts do. Nothing is redeclared here, so a change on
// either side is a type error in this file rather than a wrong screen.
//
// THREE THINGS THIS FILE DELIBERATELY DOES NOT DO.
//
//   IT DOES NOT DECIDE WHETHER A JOURNAL IS VALID. Balance, "at least two
//   lines", "exactly one of debit and kredit", "that account is not postable"
//   and "that period is closed" are the ENGINE's rules, stated once, in one
//   place, with their own codes. A second opinion in the browser would be a
//   second answer, and the one on screen would be the one nobody can
//   reconcile. The forms show a running total because an accountant needs to
//   see one; the refusal always comes from the server.
//
//   IT DOES NOT OFFER A DELETE FOR A POSTED JOURNAL, because the API has none
//   and must never have one. `batalkan` cancels a DRAFT (the engine refuses
//   anything else) and `buatPembalik` is the only correction of a POSTED
//   entry. See ADR 0010: two rows are added, none is removed.
//
//   IT DOES NOT SEND `referensiTipe`, `referensiId`, `kunciIdempotensi` OR
//   `isAutoGenerated`. The router answers 400 on each of them rather than
//   ignoring them, and `BuatJurnalInput` here is narrowed to what a form may
//   legitimately fill in, so a screen cannot send one by accident.
