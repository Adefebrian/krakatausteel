/**
 * What a FORM may fill in. Narrower than the engine's `BuatJurnalInput` on
 * purpose: see this file's header on the four fields the router refuses.
 */
export interface InputJurnalManual {
  cabangId: string;
  jenis: JenisManual;
  tanggalTransaksi: string;
  keterangan: string | null;
  baris: BarisJurnalInput[];
}

export interface FilterJurnalWeb {
  periodeId?: string | null;
  cabangId?: string | null;
  jenis?: string | null;
  status?: StatusJurnal | null;
  cari?: string | null;
  dariTanggal?: string | null;
  sampaiTanggal?: string | null;
  /** True: engine generated only. False: typed by a person only. Null: both. */
  otomatis?: boolean | null;
}

export type { FilterJurnal };

/** The document list, newest transaction first, capped at BATAS_DAFTAR_JURNAL. */
export function daftarJurnal(filter: FilterJurnalWeb = {}): Promise<Daftar<RingkasanJurnal>> {
  return apiGet(
    `/jurnal${buildQuery({
      periodeId: filter.periodeId ?? null,
      cabangId: filter.cabangId ?? null,
      jenis: filter.jenis ?? null,
      status: filter.status ?? null,
      cari: filter.cari ?? null,
      dariTanggal: filter.dariTanggal ?? null,
      sampaiTanggal: filter.sampaiTanggal ?? null,
      otomatis: filter.otomatis === null || filter.otomatis === undefined ? null : String(filter.otomatis),
    })}`,
  );
}

/**
 * One document with its lines, the accounts named, and both ends of its
 * correction pair resolved to document numbers.
 *
 * A journal in another branch answers 404 rather than 403, by design: the id
 * selects the row and the row states its own branch, so a manipulated id
 * cannot confirm that a document exists somewhere the caller may not look.
 */
export function detailJurnal(id: string): Promise<JurnalTampil> {
  return apiGet(`/jurnal/${encodeURIComponent(id)}`);
}

/** Always born DRAFT. There is no flag on this call that could post it. */
export function buatJurnal(input: InputJurnalManual): Promise<Jurnal> {
  return apiPost("/jurnal", input);
}

/**
 * Replaces the WHOLE draft, header and lines. A PUT and not a PATCH because
 * that is what the engine does: every line is deleted and rewritten, and a
 * partial merge here would be this client merging a document the engine never
 * merges.
 */
export function ubahJurnal(id: string, input: InputJurnalManual): Promise<Jurnal> {
  return apiPut(`/jurnal/${encodeURIComponent(id)}`, input);
}

/**
 * Cancels a DRAFT. `deleted_at` plus `deleted_by`: the attempt stays in the
 * database and in the audit log. Anything that is not a DRAFT is refused by
 * the engine, and a POSTED journal is corrected by `buatPembalik` alone.
 */
export function batalkanJurnal(id: string): Promise<{ id: string; dibatalkan: boolean }> {
  return apiPost(`/jurnal/${encodeURIComponent(id)}/batal`);
}

/** Checker's act. The engine refuses the journal's own author (spec 2 rule 1). */
export function verifikasiJurnal(id: string): Promise<Jurnal> {
  return apiPost(`/jurnal/${encodeURIComponent(id)}/verifikasi`);
}

/** DRAFT to POSTED. Nothing here retries: a lost race must not get a second go. */
export function postingJurnal(id: string): Promise<Jurnal> {
  return apiPost(`/jurnal/${encodeURIComponent(id)}/posting`);
}

/** Atomic. One invalid member leaves NOTHING posted (spec 6.6.8). */
export function postingBatch(ids: readonly string[]): Promise<Daftar<Jurnal>> {
  return apiPost("/jurnal/posting-batch", { ids });
}

/**
 * SPEC 9.4's "HAPUS JURNAL TRANSAKSI", AND IT IS A CREATE.
 *
 * The answer is the REVERSING journal: `jenis` REVERSAL, debit and credit
 * swapped line for line, dated in the CURRENT OPEN period because the
 * original's period may already be closed, with the original's number quoted
 * in its `keterangan`. The original is marked REVERSED and STAYS IN THE
 * LEDGER, where `v_ledger_baris` counts both halves so the pair nets to zero.
 *
 * 201 and not 200, deliberately, on the server: answering 200 would read as
 * "the delete succeeded", which is the exact misunderstanding the whole design
 * exists to prevent. The screen says the same thing in words BEFORE the click.
 */
export function buatPembalik(id: string, alasan: string): Promise<Jurnal> {
  return apiPost(`/jurnal/${encodeURIComponent(id)}/pembalik`, { alasan });
}
