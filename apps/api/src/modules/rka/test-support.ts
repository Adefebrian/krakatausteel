// apps/api/src/modules/rka/test-support.ts
//
// Reusable fixture builder for the RKA engine tests (spec 4.8, spec 9.3, spec
// 10.3 report 24, spec 16 scenarios 18 and 24). NOT a *.test.ts file, so
// `bun test` never executes it on its own.
//
// WHY THESE TESTS HIT REAL POSTGRES
// This module's job is almost entirely a claim about what the database already
// contains, and most of what it must respect lives inside Postgres:
//   - `rka_versi_uq` and `rka_baseline_uq` (migrations/0012) ARE the versioning
//     rules of spec 9.3: one row per version, AT MOST ONE DISETUJUI per scope;
//   - `trg_rka_detail_10_dimensi` ties a budget line's dimension to its budget
//     type, so a PUMK line cannot be filed against an expense account;
//   - `v_ledger_baris` (migrations/0018) IS the definition of realisation for
//     an OPEN period, including the reversal predicate of ADR 0010;
//   - `saldo_akun_periode` (migrations/0011), with its identity CHECK, is the
//     definition for a CLOSED one, and its COLUMN LIST is the reason report 24
//     cannot produce a per-sector figure for a closed period at all.
// A fake or in-memory repository proves nothing about any of that. So every
// fixture below writes to `tjsl_test`, which tools/test-env.ts guarantees is
// where DATABASE_URL points during `bun test`.
//
// WHY THE COLLABORATING ENGINES ARE REAL, WRAPPED, NEVER REPLACED
// modules/angsuran/test-support.ts records what the alternative cost: a pure
// double for the journal port hid two production-breaking defects behind
// sixteen green tests. THE RULE THAT CAME OUT OF IT, and that this file
// follows: a double may stand in for a collaborator's FAILURE, never for its
// VALIDATION.
//
// So the realisation this fixture manufactures is real:
//   - every PUMK schedule is generated by the REAL instalment engine and every
//     disbursement is posted by the REAL ledger engine through `postingEvent`;
//   - every Non PUMK grant runs the REAL Non PUMK engine's whole state machine,
//     proposal to assessment to review to approval to disbursement to LPJ, so
//     the `nonpumk_penyaluran` rows report 12 reads and the ledger lines report
//     24 reads are the same event and not two fixtures that happen to agree;
//   - the refund is posted by the REAL engine's `verifikasiLpj`, which is the
//     only thing in the system that knows a refund credits the bidang's own
//     expense account rather than the pooled one.
// THIS MODULE'S OWN ENGINE IS NEVER STOOD IN FOR. Not once. Every RKA row in
// every test is created by `d.engine`, which means a report test currently
// fails at its arrangement step, in `buatRka`, and says so. That is the correct
// failure for a tests-first suite and it names the missing method.
//
// WHY SO MUCH OF THIS RESEMBLES modules/closing/test-support.ts
// `bun tools/check-boundaries.ts` forbids a deep import into a sibling
// module's internals, and that file is internal to modules/closing. The money
// helpers, the unique-key helper, the DB port and the leak-detecting
// `tolakDengan` are therefore re-declared here with the SAME semantics. Two
// rules follow: the shapes must not drift (a sen-level difference between two
// modules' `keSen` would be a real difference in a real ledger), and when a
// shared test-support package appears, this file collapses into it.
//
// THE COA, THE EVENT MAPPINGS, THE PERMISSIONS AND THE PARAMETER CATALOGUE ARE
// THE SHIPPED ONES. `seedCoaDanEventMapping`, `seedKonfigurasiTambahan` and
// `seedRbac` from apps/api/src/seed are called directly rather than re-typed,
// and every context's permission list comes from `permissionsForRole`, which
// READS the grant matrix out of the database. A fixture that hardcodes
// `permissions: ["admin.rka"]` asserts against its own opinion; that is how
// `jurnal.update` / `jurnal.delete` being grantable to nobody stayed invisible,
// and it is how the three catalogue gaps this folder files would have stayed
// invisible too.
//
// NOTHING GLOBAL IS EVER TOUCHED. A closing test once blanked a GLOBAL
// (`bumn_id IS NULL`) `konfigurasi` row to reach a guard and poisoned every
// world that ran afterwards, in every file, for the rest of the run.
// `hapusKonfigurasi` below therefore BLANKS THIS WORLD'S OWN BUMN-SCOPED ROW,
// which reaches the same guard by the same bumn-then-global resolution order
// and cannot be observed by anybody else. It refuses outright to write a row
// with a NULL `bumn_id`. The same rule governs `sdg`, whose rows are global:
// they are inserted ON CONFLICT DO NOTHING and never updated or deleted.
//
// NO TEST MAY DEPEND ON ANOTHER TEST'S DATA. `bun run db:reset` is not run
// between files and several of these tables refuse a physical DELETE, so every
// fixture key is uniquified per call via `kunci()` and every world gets its own
// bumn, branches, chart of accounts, periods, parameter rows, sectors and
// bidang. TWO CONSECUTIVE RUNS WITHOUT A RESET THEREFORE PRODUCE IDENTICAL
// RESULTS, which ./rka-fixture.test.ts is required to demonstrate rather than
// assume.
