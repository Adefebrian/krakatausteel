// Money. BigInt minor units internally, two-decimal strings at every boundary.
// ---------------------------------------------------------------------------

/** Whole rupiah -> `Uang`. `rp(7_500_000)` === "7500000.00". */
export function rp(rupiahBulat: number): Uang {
  if (!Number.isSafeInteger(rupiahBulat)) {
    throw new Error(`rp() hanya menerima bilangan bulat: ${rupiahBulat}`);
  }
  return sen(BigInt(rupiahBulat) * 100n);
}

/** Minor units -> `Uang`. `sen(-150n)` === "-1.50". */
export function sen(minor: bigint): Uang {
  const negatif = minor < 0n;
  const abs = negatif ? -minor : minor;
  return `${negatif ? "-" : ""}${abs / 100n}.${String(abs % 100n).padStart(2, "0")}`;
}

/** `Uang` -> minor units. Throws on anything that is not exactly two decimals. */
export function keSen(nilai: Uang): bigint {
  const m = /^(-?)(\d+)\.(\d{2})$/.exec(nilai);
  if (!m) throw new Error(`bukan Uang yang valid: ${JSON.stringify(nilai)}`);
  const besar = BigInt(m[2]) * 100n + BigInt(m[3]);
  return m[1] === "-" ? -besar : besar;
}

export function jumlahUang(...nilai: Uang[]): Uang {
  return sen(nilai.reduce((acc, n) => acc + keSen(n), 0n));
}

export function kurangUang(a: Uang, b: Uang): Uang {
  return sen(keSen(a) - keSen(b));
}

export function negasiUang(a: Uang): Uang {
  return sen(-keSen(a));
}

/**
 * `realisasi / anggaran * 100`, two decimals, HALF UP away from zero.
 *
 * DECLARED HERE AND NOT ASSERTED AS A LITERAL ANYWHERE. Report 24's percentage
 * column is arithmetic, not policy, so the tests state the rule once, in this
 * function, and compare the engine against it. A test that wrote `"83.33"` by
 * hand would be asserting a rounding decision it had made in its head.
 */
export function persenCapaian(realisasi: Uang, anggaran: Uang): Persen | null {
  const bawah = keSen(anggaran);
  if (bawah === 0n) return null;
  // Scale by 10_000 = 100 (percent) * 100 (two decimals), then round half up.
  const atas = keSen(realisasi) * 10_000n;
  const negatif = atas < 0n !== bawah < 0n;
  const absAtas = atas < 0n ? -atas : atas;
  const absBawah = bawah < 0n ? -bawah : bawah;
  const dibulatkan = (absAtas + absBawah / 2n) / absBawah;
  const bertanda = negatif ? -dibulatkan : dibulatkan;
  const abs = bertanda < 0n ? -bertanda : bertanda;
  return `${bertanda < 0n ? "-" : ""}${abs / 100n}.${String(abs % 100n).padStart(2, "0")}`;
}

