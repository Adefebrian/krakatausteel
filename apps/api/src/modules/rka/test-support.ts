  /** The raw `dimensi_json` of every line of a journal, for the pin that says
   *  a PUMK disbursement carries no sector. */
  dimensiBarisJurnal(jurnalId: string): Promise<Array<Record<string, unknown>>>;

  // --- rka rows, read straight from the tables ------------------------------
  bacaRkaDb(rkaId: string): Promise<RkaDb>;
  daftarRkaDb(filter: { tahun?: number; jenis?: JenisRka }): Promise<RkaDb[]>;
  bacaBarisRkaDb(rkaId: string): Promise<BarisRkaDb[]>;

  // --- configuration knobs --------------------------------------------------
  /** Writes/updates THIS WORLD'S bumn-scoped row. Refuses a global write. */
  setelKonfigurasi(grup: string, kunciKonfig: string, nilai: string): Promise<void>;
