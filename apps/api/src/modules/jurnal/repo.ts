const KOLOM_JURNAL = `
  id, bumn_id, cabang_id, no_jurnal, jenis,
  tanggal_transaksi::text as tanggal_transaksi, periode_id, keterangan,
  referensi_tipe, referensi_id,
  total_debit::text as total_debit, total_kredit::text as total_kredit,
  status, is_auto_generated, reversal_of_jurnal_id, reversed_by_jurnal_id,
  kunci_idempotensi, verified_by, verified_at::text as verified_at,
  posted_by, posted_at::text as posted_at, created_by,
  deleted_at::text as deleted_at, version`;

function daftarPlaceholder(mulai: number, jumlah: number): string {
  return Array.from({ length: jumlah }, (_, i) => `$${mulai + i}::uuid`).join(", ");
}

