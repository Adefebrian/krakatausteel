// Every statement the journal engine issues, in one file. No business rules
// live here; the engine decides, the repo reads and writes.
//
// THIS FILE RUNS ON TWO DRIVERS. The tests build their port on `bun:sql`
// (the engine needed a transaction while core/ was mid-flight); the server
// builds it on node-postgres through core/adapters/db.ts. Every cast below is
// correct on both, but the reasons were originally written from `bun:sql`
// observations only, so read them as "why the cast is here", not as "how the
// driver behaves". Where the two differ at all (the SQLSTATE field), the
// difference is handled in ./kesalahan.ts, in one place.
//
// THREE DRIVER FACTS THIS FILE IS BUILT AROUND (verified against `bun:sql`
// 1.3.x before a line of the engine was written; each cast is also the correct
// and portable form for node-postgres, which is why nothing here changes when
// the port is swapped):
//
//  1. A `jsonb` parameter bound from a JS STRING is stored as a JSON string
//     SCALAR, not as an object: `insert ... values ($1::jsonb)` with
//     '{"a":1}' produces jsonb_typeof = 'string' and `j->>'a'` = NULL. The
//     dimensions on a journal line would silently stop being queryable. Every
//     jsonb parameter below therefore goes through `$n::text::jsonb`, and
//     every read casts `dimensi_json::text` and parses it here, so the shape
//     the engine sees never depends on driver decoding.
//  2. DATE and TIMESTAMPTZ come back as JS `Date`. Money is NUMERIC and comes
//     back as a string. So every date and timestamp is selected `::text`,
//     which keeps `tanggal_transaksi` a plain 'YYYY-MM-DD' end to end and
//     keeps amounts as the decimal strings `Uang` promises.
//  3. A JS array is serialised as a bare comma-joined string, which `uuid[]`
//     rejects. Hence `IN ($2, $3, ...)` built from a placeholder list rather
//     than `= any($2::uuid[])`.
//
// STATUS IS NEVER WRITTEN AT INSERT TIME. A journal is always INSERTed as
// DRAFT and moved to POSTED by a separate UPDATE, even when the caller wants a
// posted journal in one call (postingEvent, reversal). Inserting a row already
// POSTED and then adding its lines makes the totals trigger UPDATE a POSTED
// row, which the immutability guard of migrations/0010 rejects outright
// (TJSL-JRN-011). DRAFT first is not a style preference, it is the only order
// the schema allows.
