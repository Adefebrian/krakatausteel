describe("otorisasi: izin yang dijaga engine harus izin yang bisa diberikan", () => {
  // THE BUG CLASS THIS CLOSES. The engine used to check `jurnal.update` and
  // `jurnal.delete` while the auth catalogue carried neither, and to check
  // `jurnal.post` for reversal while `jurnal.reversal` existed and granted
  // nothing. Both stayed green for the same reason: the fixture wrote its own
  // permission arrays, so every test asserted against its own opinion instead
  // of against the grant matrix. Resolving from the database is what makes
  // "the engine demands a permission nobody can be granted" a failing test.
  test("setiap izin yang dijaga engine ada di katalog auth", async () => {
    for (const kode of Object.values(PERMISSION_JURNAL)) {
      // A typo here is a permanent 403 that reads like a policy decision.
      expect(canonicalPermission(kode)).toBe(kode);
    }
  });

  test("setiap izin yang dijaga engine benar benar dipegang minimal satu role di database", async () => {
    // Through the pg adapter on purpose: seedRbac binds a text[] parameter,
    // and node-postgres serialises a JS array correctly where a bare
    // comma-joined string would be rejected.
    const dbPg = createDbAdapter();
    await seedRbac(dbPg);

    const diberikan = new Set<string>();
    for (const role of ROLE_CODES) {
      for (const kode of await permissionsForRole(dbPg, role)) diberikan.add(kode);
    }

    for (const kode of Object.values(PERMISSION_JURNAL)) {
      // If this fails, the engine is guarding a door with a key that does not
      // exist: the operation is unreachable for every role in the system.
      expect(diberikan.has(kode)).toBe(true);
    }

    // And the two the engine treats as distinct really are distinct rights in
    // the matrix, held by the role that reverses rather than by everyone who
    // can post.
    const approver = await permissionsForRole(dbPg, "APPROVER");
    expect(approver).toContain(PERMISSION_JURNAL.POSTING);
    expect(approver).toContain(PERMISSION_JURNAL.REVERSAL);
    const maker = await permissionsForRole(dbPg, "MAKER");
    expect(maker).toContain(PERMISSION_JURNAL.BUAT);
    expect(maker).not.toContain(PERMISSION_JURNAL.POSTING);
    expect(maker).not.toContain(PERMISSION_JURNAL.REVERSAL);
  }, 30_000);
});

describe("otorisasi: reversal adalah hak tersendiri", () => {
  test("pemegang jurnal.post tanpa jurnal.reversal tidak boleh membalik jurnal", async () => {
    // `jurnal.reversal` exists in the auth catalogue and drives its own nav
    // item. If the engine checked `jurnal.post` instead, that permission would
    // grant nothing and every user who can post would silently also be able to
    // reverse a posted journal. In the shipped APPROVER role the two travel
    // together, so this changes nobody's access today; it makes them
    // separable, which is the only reason to have two codes.
    const draft = await engine.buatJurnal(
      {
        cabangId: d.cabangId,
        jenis: "UMUM",
        tanggalTransaksi: d.tanggalKini,
        keterangan: "uji hak reversal",
        baris: [
          { akunId: d.akun.kas.id, debit: rp(88_000) },
          { akunId: d.akun.pendapatanAlokasi.id, kredit: rp(88_000) },
        ],
      },
      d.ctx.approver,
    );
    const posted = await engine.postingJurnal(draft.id, d.ctx.approver);

    const hanyaPosting = {
      ...d.ctx.approver,
      permissions: d.ctx.approver.permissions.filter((p) => p !== "jurnal.reversal"),
    };
    expect(hanyaPosting.permissions).toContain("jurnal.post");
    await tolakDengan(
      engine.reversalJurnal(posted.id, "tanpa hak reversal", hanyaPosting),
      KODE_JURNAL.TIDAK_BERWENANG,
    );
    // Untouched: a refused reversal must not half-apply.
    const db = await bacaJurnalDb(d.db, posted.id);
    expect(db?.status).toBe("POSTED");
    expect(db?.reversed_by_jurnal_id).toBeNull();

    // The same user WITH the right succeeds, which is what proves the refusal
    // was about the permission and not about the journal.
    const rev = await engine.reversalJurnal(posted.id, "dengan hak reversal", d.ctx.approver);
    expect(rev.jenis).toBe("REVERSAL");
  });
});

describe("spec 7.2 atomicity: jurnal gabungan hidup di transaksi pemanggil", () => {
  test("kalau langkah pemanggil setelah jurnal gagal, jurnal gabungan ikut hilang", async () => {
    // This is the requirement in spec 7.2's own words: "Seluruh langkah 1
    // sampai 8 dalam satu transaksi database. Kalau jurnal gagal, alokasi
    // harus rollback." The reverse must hold too, or a failed allocation
    // leaves a real posted journal behind.
    let idJurnal = "";
    const sebelum = await selisihLedger(d.db);

    let gagal = false;
    try {
      await d.db.transaction(async (tx) => {
        const hasil = await engine.postingEventGabungan(
          {
            cabangId: d.cabangId,
            tanggalTransaksi: d.tanggalKini,
            komponen: komponenSetoran(rp(900_000), rp(90_000)),
          },
          tx,
          d.ctx.maker,
        );
        idJurnal = hasil.jurnalId;
        // Stand-in for a later allocation step refusing (an outstanding that
        // would go negative, a schedule row already settled).
        throw new Error("langkah alokasi berikutnya menolak");
      });
    } catch (e) {
      gagal = true;
      expect((e as Error).message).toContain("langkah alokasi berikutnya menolak");
    }

    expect(gagal).toBe(true);
    expect(idJurnal).not.toBe("");
    // The journal it had already written is gone, not merely unposted.
    expect(await bacaJurnalDb(d.db, idJurnal)).toBeNull();
    expect(await selisihLedger(d.db)).toBe(sebelum);
  });

  test("penolakan balance yang datang di transaksi pemanggil tetap jadi domain error bersih", async () => {
    // The balance guard is a DEFERRED trigger: on this path it would otherwise
    // only speak when the CALLER commits, far outside any `try` this module
    // owns, and the caller would receive raw trigger text it cannot translate.
    // The engine forces the guard to fire before it returns, so the refusal
    // arrives here as a JurnalError. The unbalanced journal below is written by
    // hand, blessed as 'seed' so the bypass is visible in the data, and stands
    // for the real case: something else in the caller's transaction left a
    // POSTED journal that does not balance.
    let ditangkap: unknown;
    try {
      await d.db.transaction(async (tx) => {
        await tx.query(`select set_config('tjsl.jalur_posting', 'seed:' || txid_current(), true)`);
        // DRAFT first, lines, then the POSTED flip. Any other order makes the
        // totals trigger UPDATE a POSTED row, which the immutability guard
        // refuses (TJSL-JRN-011) before the balance guard ever gets a turn.
        const rusak = await tx.query<{ id: string }>(
          `insert into jurnal (bumn_id, cabang_id, no_jurnal, jenis, tanggal_transaksi, periode_id, status)
           values ($1, $2, $3, 'UMUM', $4, $5, 'DRAFT') returning id`,
          [d.bumnId, d.cabangId, kunci("RAW-POSTED"), d.tanggalKini, d.periodeKini.id],
        );
        await tx.query(
          `insert into jurnal_baris (jurnal_id, urutan, akun_id, debit) values ($1, 1, $2, $3)`,
          [rusak[0].id, d.akun.kas.id, rp(5_000_000)],
        );
        await tx.query(
          `insert into jurnal_baris (jurnal_id, urutan, akun_id, kredit) values ($1, 2, $2, $3)`,
          [rusak[0].id, d.akun.pendapatanAlokasi.id, rp(4_999_999)],
        );
        await tx.query(
          `update jurnal set status = 'POSTED', posted_by = $2, posted_at = now() where id = $1`,
          [rusak[0].id, d.ctx.maker.userId],
        );

        await engine.postingEventGabungan(
          {
            cabangId: d.cabangId,
            tanggalTransaksi: d.tanggalKini,
            komponen: komponenSetoran(rp(10_000), rp(1_000)),
          },
          tx,
          d.ctx.maker,
        );
      });
    } catch (e) {
      ditangkap = e;
    }

    expect(ditangkap).toBeInstanceOf(JurnalError);
    const err = ditangkap as JurnalError;
    expect(err.kode).toBe(KODE_JURNAL.TIDAK_BALANCE);
    // The raw trigger text is kept for the log and kept OUT of the message.
    expect(err.penyebabDb ?? "").toContain("TJSL-JRN-031");
    expect(err.message).not.toContain("TJSL-JRN-031");
    expect(err.message).not.toMatch(/PL\/pgSQL|SQLSTATE|violates/i);
    expect(await selisihLedger(d.db)).toBe("0.00");
  });
});

