// Combined event posting (spec 7.2 step 8), the audit trail, and the DRIVER
// the server actually runs on.
//
// WHY THIS FILE EXISTS SEPARATELY FROM THE OTHER SEVEN
// The engine tests written first all construct the engine from `bun:sql`,
// because that is what test-support.ts builds the port from. That left the
// production path, node-postgres through core/adapters/db.ts, with no coverage
// at all, and the two drivers do not agree on where they put a SQLSTATE
// (`errno` vs `code`). A whole branch of ./kesalahan.ts was therefore dead in
// production while every test stayed green. The last describe block closes
// that: it drives the SAME engine through `createDbAdapter()`, and one test
// pins the SQLSTATE reader against both driver error shapes directly.
//
// WHAT IS DELIBERATELY NOT ASSERTED HERE
// A component contributes a debit AND a credit of its own value, so an
// assembled combined journal cannot be unbalanced by any input a caller can
// express. The balance gate is asserted anyway (the engine runs the same spec
// 6.2 check over the merged lines), and what IS tested below is the thing that
// would actually break: that a balance refusal ARRIVING ON THIS PATH becomes a
// clean domain error inside the call, rather than raw trigger text at a COMMIT
// this module does not own. Writing a fake "unbalanced components" case would
// be asserting against a shape the API cannot produce.
