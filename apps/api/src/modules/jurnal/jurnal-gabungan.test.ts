/** The three components of a deposit allocation, spec 7.2's own example. */
function komponenSetoran(
  pokok: string,
  jasa: string,
  kelebihan?: string,
): KomponenEvent[] {
  const daftar: KomponenEvent[] = [
    { eventCode: "ANGSURAN_POKOK", nilai: pokok, mitraId: d.mitraId, akadId: d.akadId },
    { eventCode: "ANGSURAN_JASA_ADM", nilai: jasa },
  ];
  if (kelebihan) daftar.push({ eventCode: "TERIMA_KELEBIHAN_ANGSURAN", nilai: kelebihan });
  return daftar;
}

