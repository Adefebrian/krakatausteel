/**
 * One row of the document list (spec 9.4 "Daftar Jurnal").
 *
 * NAMES, NOT ONLY IDS, for the three people a journal records: who filed it,
 * who verified it and who posted it. "Who posted this" answered with a uuid is
 * answered only for somebody with database access, and that question is the
 * whole reason the list exists.
 *
 * `jalurPosting` is the provenance column ADR 0012 stamps on every row:
 * `ENGINE`, `SEED`, `IMPORT_SALDO_AWAL` or `LEGACY`. A screen that could not
 * see it would present an opening-balance import and an operator's entry as
 * the same kind of document.
 */
export interface RingkasanJurnal {
  id: string;
  noJurnal: string;
  jenis: JenisJurnal;
  tanggalTransaksi: string;
  periodeId: string;
  periodeLabel: string;
  cabangId: string;
  cabangKode: string;
  cabangNama: string;
  keterangan: string | null;
  referensiTipe: string | null;
  referensiId: string | null;
  totalDebit: Uang;
  totalKredit: Uang;
  status: StatusJurnal;
  isAutoGenerated: boolean;
  jalurPosting: string | null;
  reversalOfJurnalId: string | null;
  reversedByJurnalId: string | null;
  dibuatOleh: string | null;
  diverifikasiOleh: string | null;
  verifiedAt: string | null;
  dipostingOleh: string | null;
  postedAt: string | null;
  jumlahBaris: number;
  version: number;
}

/** One line of a journal, with the account it hits named rather than pointed at. */
export interface BarisJurnalTampil extends BarisJurnal {
  akunKode: string;
  akunNama: string;
  mitraNama: string | null;
  akadNo: string | null;
}

/**
 * One document, opened.
 *
 * `pembalik` and `dibalikOleh` are the two ends of ADR 0010's correction pair,
 * resolved to their document numbers: a REVERSED journal must be readable as
 * "still in the ledger, offset by THAT one", and a REVERSAL must name what it
 * offsets. Printing only the uuids would leave the most important fact on the
 * page unreadable.
 */
export interface JurnalTampil extends RingkasanJurnal {
  baris: BarisJurnalTampil[];
  /** The original this journal reverses, when `jenis` is REVERSAL. */
  pembalik: { id: string; noJurnal: string } | null;
  /** The reversing journal that offsets this one, when `status` is REVERSED. */
  dibalikOleh: { id: string; noJurnal: string } | null;
}

export interface FilterJurnal {
  periodeId: string | null;
  cabangId: string | null;
  jenis: JenisJurnal | null;
  status: StatusJurnal | null;
  /** `no_jurnal` or `keterangan`, case-insensitive substring. */
  cari: string | null;
  dariTanggal: string | null;
  sampaiTanggal: string | null;
  /** Manual entries only (`false`), event-generated only (`true`), or both. */
  otomatis: boolean | null;
}

export interface JurnalBaca {
  /** The document list, newest transaction first. Never more than `BATAS_DAFTAR`. */
  daftar(filter: FilterJurnal, ctx: JurnalContext): Promise<RingkasanJurnal[]>;
  /** One document with its lines, or `JURNAL_TIDAK_DITEMUKAN`. */
  detail(id: string, ctx: JurnalContext): Promise<JurnalTampil>;
}

/**
 * The list ceiling, the same 500 modules/pumk's read models use. A journal list
 * is unbounded by nature (a year of a busy branch is tens of thousands of
 * documents) and an endpoint that will serialise all of them on request is a
 * way to make one GET hold a connection and a heap. The filters above are how
 * an operator narrows it; the screen shows the ceiling when it is hit.
 */
export const BATAS_DAFTAR = 500;

