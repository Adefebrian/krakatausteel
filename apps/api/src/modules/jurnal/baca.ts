/**
 * Fails closed on an unregistered code, exactly as ./service.ts's `wajibPunya`
 * does and for the same reason: a code the shipped catalogue does not know is a
 * configuration fault, and reporting it as TIDAK_BERWENANG would dress it up as
 * a policy decision and hide it forever.
 *
 * The router already ran `requirePermission`, so this is the second line. It
 * stays because a read model reachable from a later batch job or a fixture must
 * refuse on its own evidence rather than on its caller's good manners.
 */
function wajibIzin(ctx: JurnalContext, kode: string): void {
  const kanonik = canonicalPermission(kode);
  if (!kanonik) {
    throw new JurnalError(
      "TIDAK_BERWENANG",
      `Kewenangan "${kode}" belum terdaftar di katalog izin, jadi tindakan ini ditolak sampai kewenangannya ditambahkan.`,
      { permission: kode },
    );
  }
  if (!ctx.permissions.includes(kanonik)) {
    throw new JurnalError(
      "TIDAK_BERWENANG",
      "Pengguna ini tidak punya wewenang untuk melihat jurnal.",
      { permission: kanonik },
    );
  }
}

function cabangTerlihat(ctx: JurnalContext): string[] {
  return [...new Set<string>([ctx.cabangId, ...(ctx.cabangDalamScope ?? [])])];
}

/** `$3::uuid, $4::uuid, ...`. See the driver note in this file's header. */
function daftarPlaceholder(mulai: number, jumlah: number): string {
  return Array.from({ length: jumlah }, (_, i) => `$${mulai + i}::uuid`).join(", ");
}

