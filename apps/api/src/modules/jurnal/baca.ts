// Read models for the journal HTTP surface (spec 9.4), and nothing else.
//
// WHY THIS FILE EXISTS SEPARATELY FROM ./service.ts
// `JurnalEngine` is the WRITE surface of spec 6: it creates, edits, verifies,
// posts, cancels and reverses, and every one of its reads is a read INSIDE a
// transaction it is about to write in. The seven screens of spec 9.4 need
// something the engine has no business carrying: the document list an operator
// filters, the DRAFT queue a Checker works through, the POSTED list an Approver
// reverses from, and one document with its lines and their account names. Those
// are projections, not behaviour, so they live here rather than widening an
// engine whose nine test files pin its current shape.
//
// IT FOLLOWS modules/closing/baca.ts AND modules/pumk/baca.ts, and obeys the
// same three rules:
//
// 1. BRANCH SCOPE COMES FROM THE SESSION, NEVER FROM THE REQUEST. Every query
//    below is filtered by the branches the SESSION resolved. The by-id read
//    checks the branch the ROW reports and answers `JURNAL_TIDAK_DITEMUKAN`
//    rather than a scope refusal, for the reason modules/mitra gives about an
//    akad: a 403 there would confirm that the id names a real document in
//    another branch, which is the enumeration branch scope exists to prevent.
//
// 2. IT WRITES NOTHING. Every function here is a SELECT, gated by
//    `jurnal.view`, which every operational role holds and which grants no
//    power to create, verify, post or reverse anything. That is what lets an
//    Auditor open the journal screens (spec 16 scenario 23) with no code that
//    can change a line.
//
// 3. NO SECOND OPINION ABOUT THE LEDGER. Totals are read from the stored
//    `jurnal.total_debit` / `total_kredit`, which migrations/0010's trigger
//    maintains from the lines themselves; nothing here re-sums a journal and
//    nothing here decides whether a line counts. A BALANCE read is
//    `v_ledger_baris`'s job (ADR 0010) and is not this file's business: these
//    are DOCUMENTS, listed by status, including the DRAFTs that are not in the
//    ledger at all.
//
// DRIVER FACTS, the same three ./repo.ts is built around, because this file
// runs on both drivers too: DATE and TIMESTAMPTZ come back as `Date` so every
// one is selected `::text`; `dimensi_json` is read `::text` and parsed here; a
// JS array binds as a comma-joined string, so branch lists are expanded into a
// placeholder list rather than passed to `= any($n::uuid[])`.
import { canonicalPermission } from "../auth/index";
import {
  JurnalError,
  PERMISSION_JURNAL,
  type BarisJurnal,
  type DimensiBaris,
  type JenisJurnal,
  type JurnalContext,
  type JurnalDbPort,
  type StatusJurnal,
  type Uang,
} from "./contract";

export interface JurnalBacaDeps {
  db: JurnalDbPort;
}

