/**
 * Fragments that mean a raw driver or trigger string has leaked into a
 * user-facing message. The module must wrap DB failures in `ClosingError` with
 * a clean Indonesian message and keep the raw text in `penyebabDb`.
 */
const POLA_KEBOCORAN_DB =
  /TJSL-[A-Z]{3}-\d{3}|PL\/pgSQL|plpgsql|SQLSTATE|violates|duplicate key|null value in column|relation "|_ck\b|_uq\b|ERROR:|syntax error at/i;

/**
 * Asserts a rejection is the expected DOMAIN error, and that its message is
 * free of DB internals. DELIBERATELY STRICT ABOUT THE TYPE AND THE CODE: the
 * stub in ./service.ts throws a plain `Error`, so this cannot be satisfied by
 * an unimplemented engine, which is the one failure mode a tests-first suite
 * exists to prevent.
 *
 * TAKES A PROMISE OR A THUNK. Prefer the thunk. A method that rejects from a
 * guard clause placed before its first `await`, in a function not declared
 * `async`, throws SYNCHRONOUSLY: the argument expression blows up at the call
 * site and this assertion never runs, so the test fails with a raw stack
 * instead of "expected KODE_X, got KODE_Y". That is exactly how today's stub
 * behaves, and it is a shape a real implementation can reach by accident.
 */
export async function tolakDengan(
  janji: Promise<unknown> | (() => Promise<unknown> | unknown),
  kode: KodeClosing,
): Promise<ClosingError> {
  let ditangkap: unknown;
  try {
    await (typeof janji === "function" ? janji() : janji);
  } catch (e) {
    ditangkap = e;
  }
  if (ditangkap === undefined) {
    throw new Error(`diharapkan ditolak dengan ${kode}, tapi operasi berhasil`);
  }
  expect(ditangkap).toBeInstanceOf(ClosingError);
  const err = ditangkap as ClosingError;
  expect(err.kode).toBe(kode);
  expect(err.message.length).toBeGreaterThan(0);
  expect(err.message).not.toMatch(POLA_KEBOCORAN_DB);
  return err;
}

/** Sanity: every code a test names exists in the contract's catalogue. */
export function kodeAda(kode: KodeClosing): KodeClosing {
  expect(Object.values(KODE_CLOSING)).toContain(kode);
  return kode;
}

/**
 * A prerequisite reason has to be readable by an accountant: spec 16
 * scenario 12 asks for "alasan yang jelas". So it must be non-trivially long,
 * free of driver internals, and free of the raw identifiers a developer would
 * leave behind.
 */
export function alasanTerbaca(alasan: string): void {
  expect(alasan.length).toBeGreaterThan(15);
  expect(alasan).not.toMatch(POLA_KEBOCORAN_DB);
  expect(alasan).not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}/i);
  expect(alasan).not.toMatch(/undefined|null|\[object/i);
}
