export const PESAN_JURNAL_GAGAL =
  "ledger tidak tersedia (fixture: kegagalan yang di-arm, bukan kegagalan nyata)";

/**
 * A RECORDING WRAPPER around the REAL ledger engine, not a substitute for it.
 * Every successful call is delegated; only a call explicitly armed with
 * `gagalkan` throws, and it throws BEFORE reaching the engine so nothing is
 * half-written. That is the only shape of double this repo allows: arming a
 * collaborator's failure is how a rollback becomes testable, answering in its
 * place is how two production defects once hid behind sixteen green tests.
 */
export function porterJurnalUji(db: ClosingDbPort, jam: () => Date): PorterJurnalUji {
  const { engine } = createJurnalModule({ db, jam });
  const panggilan: PanggilanJurnal[] = [];
  const armed = new Map<string, string>();

  return {
    panggilan,
    gagalkan(eventCode, pesan = PESAN_JURNAL_GAGAL) {
      armed.set(eventCode, pesan);
    },
    reset() {
      panggilan.length = 0;
      armed.clear();
    },
    async postingEvent(eventCode, payload, ctx, tx) {
      panggilan.push({ metode: "postingEvent", eventCode, argumen: payload });
      const pesan = armed.get(eventCode);
      if (pesan) {
        armed.delete(eventCode);
        throw new Error(pesan);
      }
      void tx;
      return engine.postingEvent(eventCode, payload, ctx as JurnalContext);
    },
  };
}

/** A RECORDING WRAPPER around the REAL audit service, same rule. */
export function pencatatAuditUji(db: ClosingDbPort): PencatatAuditUji {
  const service = createAuditService({ db });
  const panggilan: PanggilanAudit[] = [];
  return {
    panggilan,
    reset() {
      panggilan.length = 0;
    },
    async record(entry, runner) {
      panggilan.push({
        aksi: entry.aksi,
        entitas: entry.entitas,
        entitasId: entry.entitasId ?? null,
        hasil: entry.hasil,
        keterangan: entry.keterangan ?? null,
      });
      return service.record(entry, runner);
    },
  };
}

