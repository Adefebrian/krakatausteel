// apps/api/src/modules/closing/test-support.ts
//
// Reusable fixture builder for the closing engine tests (spec 8). NOT a
// *.test.ts file, so `bun test` never executes it on its own.
//
// WHY THESE TESTS HIT REAL POSTGRES
// Closing is the one engine whose correctness is almost entirely a claim about
// what the database already contains, and most of what it must respect lives
// inside Postgres:
//   - invariant 6, sequential close, and the reopen ordering + mandatory
//     reason, as `trg_periode_10_transisi` (migrations/0007);
//   - invariant 5, no posting into a CLOSED period (migrations/0010, 0018);
//   - invariant 13, one snapshot per akad per period, as
//     `kolektibilitas_snapshot_uq`, and one committed run per scope as
//     `closing_kolektibilitas_selesai_uq` (migrations/0011);
//   - the arithmetic of spec 8.2 step 3 and of the frozen trial balance, as
//     CHECK constraints (`penyisihan_periode_beban_ck`,
//     `saldo_akun_periode_identitas_ck`);
//   - `v_ledger_baris` and `v_rekonsiliasi_piutang`, which ARE the definition
//     of the two numbers closing freezes and the one it reconciles.
// A fake or in-memory repository proves nothing about any of that. So every
// fixture below writes to `tjsl_test`, which tools/test-env.ts guarantees is
// where DATABASE_URL points during `bun test`.
//
// WHY THE COLLABORATING ENGINES ARE REAL, WRAPPED, NEVER REPLACED
// modules/angsuran/test-support.ts records what the alternative cost: a pure
// double for the journal port hid two production-breaking defects behind
// sixteen green tests. THE RULE THAT CAME OUT OF IT, and that this file
// follows: a double may stand in for a collaborator's FAILURE, never for its
// VALIDATION. `porterJurnalUji` below is a RECORDING WRAPPER around the engine
// reached through `../jurnal/index` (the import the boundary checker allows and
// the wiring the composition root uses). It records calls and can be armed to
// fail; it never answers in the real engine's place. Every schedule is
// generated by the real instalment engine and every deposit is allocated by it,
// so the arrears this fixture manufactures are arrears the rest of the system
// agrees exist.
//
// WHY SO MUCH OF THIS RESEMBLES modules/pumk/test-support.ts
// `bun tools/check-boundaries.ts` forbids a deep import into a sibling
// module's internals, and that file is internal to modules/pumk. The money
// helpers, the unique-key helper, the DB port and the leak-detecting
// `tolakDengan` are therefore re-declared here with the SAME semantics. Two
// rules follow: the shapes must not drift (a sen-level difference between two
// modules' `keSen` would be a real bug in a real ledger), and when a shared
// test-support package appears, this file collapses into it.
//
// THE COA, THE EVENT MAPPINGS, THE PERMISSIONS AND THE PARAMETER CATALOGUE ARE
// THE SHIPPED ONES. `seedCoaDanEventMapping`, `seedKonfigurasiTambahan` and
// `seedRbac` from apps/api/src/seed are called directly rather than re-typed,
// and every context's permission list comes from `permissionsForRole`, which
// READS the grant matrix out of the database. A fixture that hardcodes
// `permissions: ["admin.closing.periode"]` asserts against its own opinion;
// that is how `jurnal.update` / `jurnal.delete` being grantable to nobody
// stayed invisible.
//
// NO TEST MAY DEPEND ON ANOTHER TEST'S DATA. `bun run db:reset` is run
// periodically by other agents and nothing here is cleaned up afterwards
// (physical DELETE is blocked on several of these tables by design), so every
// fixture key is uniquified per call via `kunci()` and every world gets its own
// bumn, branches, chart of accounts, periods, parameter rows, kolektibilitas
// ranges and allowance rates. TWO CONSECUTIVE RUNS WITHOUT A RESET THEREFORE
// PRODUCE IDENTICAL RESULTS, which is a property this suite is required to
// demonstrate rather than assume.
