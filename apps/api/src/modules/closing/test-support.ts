  // is what makes closing it legal at all: invariant 6 has nothing earlier to
  // complain about.
  // ONE statement, not twenty-four round trips. `generate_series` builds the
  // month windows in Postgres, which is also the only place that agrees with
  // `periode_window_ck` about what the last day of a month is without a second
  // implementation of the calendar in TypeScript.
